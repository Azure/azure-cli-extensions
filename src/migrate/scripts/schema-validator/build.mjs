// Rebuild with npm ci && npm run build in this directory.
import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const vendor = new URL('../../azext_migrate/runbook/configure/vendor/', import.meta.url);
const license = await readFile(new URL('LICENSE', vendor), 'utf8');
await build({
  stdin: {
    contents: "export { Validator } from '@cfworker/json-schema'; export { default as metaSchema } from './draft07.json';",
    resolveDir: fileURLToPath(new URL('.', import.meta.url)),
    sourcefile: 'schema-validator.js'
  },
  bundle: true,
  minify: true,
  format: 'iife',
  globalName: 'RunbookSchema',
  target: 'es2020',
  outfile: fileURLToPath(new URL('json-schema.js', vendor)),
  banner: { js: `/*! @cfworker/json-schema 4.1.1. Generated by scripts/schema-validator/build.mjs.\n${license}*/` }
});
